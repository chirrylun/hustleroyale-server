// Copies the floor generator and navigation from the web app so the server builds exactly the same maps.
// Usage: node scripts/sync-world.mjs [path-to-web-repo]   (default: ../hustleroyale-web)
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const web = resolve(process.argv[2] ?? "../hustleroyale-web");
const out = resolve("src/world");
mkdirSync(out, { recursive: true });
const banner = "// GENERATED by scripts/sync-world.mjs from the web repo. Do not edit here; change the web file and re-sync.\n";

for (const t of ["grass", "cave", "swamp", "ice"]) copyFileSync(`${web}/src/lib/world/props_${t}.json`, `${out}/props_${t}.json`);

let nav = readFileSync(`${web}/src/lib/guild-nav.ts`, "utf8");
writeFileSync(`${out}/guild-nav.ts`, banner + nav);

let floor = readFileSync(`${web}/src/lib/world/floor.ts`, "utf8");
floor = floor
  .replace(/from "\.\/(props_\w+)\.json"/g, 'from "./$1.json" with { type: "json" }')
  .replace('from "../guild-nav"', 'from "./guild-nav.js"');
writeFileSync(`${out}/floor.ts`, banner + floor);
copyFileSync(`${web}/src/lib/gearArt.json`, `${out}/gearArt.json`);
let look = readFileSync(`${web}/src/lib/look.ts`, "utf8");
look = look.replace('from "./gearArt.json"', 'from "./gearArt.json" with { type: "json" }');
writeFileSync(`${out}/look.ts`, banner + look);
console.log("world synced from", web);
